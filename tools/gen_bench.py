"""Generate the Forge gas-benchmark test from the vector audit + artifacts.

Reads:
  vectors/merkle_vectors.json  — trees, roots, multiproof vectors.
  out/BenchHarness.bin         — creation bytecode of the Fe harness.
  out/MerkleDistributor.bin    — creation bytecode of the demo contract.
  out/*.runtime.bin            — runtime code sizes (reported, not embedded).

Writes:
  bench/test/Bench.t.sol       — self-contained Forge test: the Fe bytecode
                                 is embedded as hex literals, so the test
                                 always measures the exact artifacts
                                 `fe build` produced. Regenerate after any
                                 Fe change: `fe build && python3
                                 tools/gen_bench.py && cd bench && forge test`.

Single proofs are recomputed here from the audited leaves with the same
tree builder the vector generator uses (imported, not duplicated).
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from gen_merkle_vectors import build_levels, single_proof
from keccak_oracle import hex_word

ROOT = Path(__file__).parent.parent


def load_tree(audit: dict, n: int) -> dict:
    for t in audit["trees"]:
        if t["n"] == n:
            return t
    raise AssertionError(f"no tree with n={n}")


def find_vector(audit: dict, name: str) -> dict:
    for v in audit["vectors"]:
        if v["name"] == name:
            return v
    raise AssertionError(f"vector {name} not in audit file")


def sol_address(word_hex: str) -> str:
    """A 32-byte ABI word rendered as a 20-byte Solidity address literal."""
    assert word_hex.startswith("0x") and len(word_hex) == 66
    assert word_hex[2:26] == "0" * 24, f"address word has dirty high bits: {word_hex}"
    return "0x" + word_hex[26:]


def sol_u256_array(name: str, values: list[str]) -> str:
    lines = [f"    uint256[] memory {name} = new uint256[]({len(values)});"]
    for i, v in enumerate(values):
        lines.append(f"    {name}[{i}] = {v};")
    return "\n".join(lines)


def sol_bytes32_array(name: str, values: list[str]) -> str:
    lines = [f"    bytes32[] memory {name} = new bytes32[]({len(values)});"]
    for i, v in enumerate(values):
        lines.append(f"    {name}[{i}] = bytes32({v});")
    return "\n".join(lines)


def sol_bool_array(name: str, values: list[bool]) -> str:
    lines = [f"    bool[] memory {name} = new bool[]({len(values)});"]
    for i, v in enumerate(values):
        lines.append(f"    {name}[{i}] = {'true' if v else 'false'};")
    return "\n".join(lines)


def main() -> None:
    audit = json.loads((ROOT / "vectors" / "merkle_vectors.json").read_text())
    harness_bin = (ROOT / "out" / "BenchHarness.bin").read_text().strip()
    dist_bin = (ROOT / "out" / "MerkleDistributor.bin").read_text().strip()
    harness_rt = (ROOT / "out" / "BenchHarness.runtime.bin").read_text().strip()
    dist_rt = (ROOT / "out" / "MerkleDistributor.runtime.bin").read_text().strip()
    assert harness_bin and dist_bin, "run `fe build` first"
    print(f"harness creation {len(harness_bin) // 2} bytes, runtime {len(harness_rt) // 2} bytes")
    print(f"distributor creation {len(dist_bin) // 2} bytes, runtime {len(dist_rt) // 2} bytes")

    trees = {n: load_tree(audit, n) for n in (2, 4, 8, 16)}

    # Single proofs for leaf 0 of each tree, recomputed from audited leaves.
    singles = {}
    for n, tree in trees.items():
        leaves = [bytes.fromhex(x[2:]) for x in tree["leaves"]]
        levels = build_levels(leaves)
        assert hex_word(int.from_bytes(levels[-1][0], "big")) == tree["root"]
        proof = single_proof(levels, 0)
        singles[n] = {
            "root": tree["root"],
            "leaf": tree["leaves"][0],
            "proof": [hex_word(int.from_bytes(p, "big")) for p in proof],
        }

    # Multiproof cases: (tree n, subset name suffix, label).
    multi_cases = [
        (8, "0", "n8_k1"),
        (8, "0_1", "n8_k2"),
        (8, "0_1_2_3", "n8_k4"),
        (8, "0_1_2_3_4_5_6_7", "n8_k8"),
        (16, "0", "n16_k1"),
        (16, "0_1", "n16_k2"),
        (16, "0_1_2_3_4_5_6_7", "n16_k8"),
        (16, "0_1_2_3_4_5_6_7_8_9_10_11_12_13_14_15", "n16_k16"),
    ]
    multis = []
    for n, suffix, label in multi_cases:
        v = find_vector(audit, f"mp_{n}_subset_{suffix}")
        multis.append({"label": label, "n": n, **v})

    tree8 = trees[8]
    allocs8 = tree8["allocations"]

    out: list[str] = []
    out.append("// SPDX-License-Identifier: MIT")
    out.append("// GENERATED by tools/gen_bench.py — do not edit by hand.")
    out.append("// The Fe bytecode below is embedded from out/*.bin (produced by")
    out.append("// `fe build`), so this test measures the exact compiled artifacts.")
    out.append("// Vector data comes from vectors/merkle_vectors.json.")
    out.append("pragma solidity ^0.8.24;")
    out.append("")
    out.append('import {Test, console} from "forge-std/Test.sol";')
    out.append('import {OzVerifier} from "../src/OzVerifier.sol";')
    out.append("")
    out.append("interface IBenchHarness {")
    out.append("    function verifySingle(uint256[] calldata proof, uint256 root, uint256 leaf) external returns (bool);")
    out.append("    function verifyMulti(uint256[] calldata proof, bool[] calldata proofFlags, uint256 root, uint256[] calldata leaves) external returns (bool);")
    out.append("    function mulDivNearest(uint256 a, uint256 b, uint256 d) external returns (uint256);")
    out.append("    function mulDivFloor(uint256 a, uint256 b, uint256 d) external returns (uint256);")
    out.append("    function wadMulNearest(uint256 a, uint256 b) external returns (uint256);")
    out.append("    function wadMulFloor(uint256 a, uint256 b) external returns (uint256);")
    out.append("    function powSigned(uint256 base, int256 exp) external returns (uint256);")
    out.append("    function compound(uint256 principal, uint256 rate, uint256 periods) external returns (uint256);")
    out.append("    function leafFromWords(uint256 index, address account, uint256 amount) external returns (uint256);")
    out.append("}")
    out.append("")
    out.append("interface IDistributor {")
    out.append("    function fund() external payable returns (uint256);")
    out.append("    function claim(uint256[] calldata proof, uint256 index, address account, uint256 amount) external returns (uint256);")
    out.append("    function claimMulti(uint256[] calldata proof, bool[] calldata proofFlags, uint256[] calldata indices, address[] calldata accounts, uint256[] calldata amounts) external returns (uint256);")
    out.append("    function root() external returns (uint256);")
    out.append("    function isClaimed(uint256 index) external returns (bool);")
    out.append("    function totalClaimed() external returns (uint256);")
    out.append("}")
    out.append("")
    out.append("contract BenchTest is Test {")
    out.append("    IBenchHarness harness;")
    out.append("    OzVerifier oz;")
    out.append("")
    out.append(f"    function harnessBin() internal pure returns (bytes memory) {{ return hex\"{harness_bin}\"; }}")
    out.append(f"    function distBin() internal pure returns (bytes memory) {{ return hex\"{dist_bin}\"; }}")
    out.append("")
    out.append("    function deploy(bytes memory code, bytes memory args) internal returns (address a) {")
    out.append("        bytes memory init = abi.encodePacked(code, args);")
    out.append("        assembly { a := create(0, add(init, 0x20), mload(init)) }")
    out.append('        require(a != address(0), "deploy failed");')
    out.append("    }")
    out.append("")
    out.append("    function setUp() public {")
    out.append("        vm.deal(address(this), 100 ether);")
    out.append("        harness = IBenchHarness(deploy(harnessBin(), \"\"));")
    out.append("        oz = new OzVerifier();")
    out.append("    }")
    out.append("")
    out.append("    function deployDistributor(uint256 root_) internal returns (IDistributor) {")
    out.append("        bytes memory args = abi.encode(root_, uint256(0), uint256(0), uint256(0));")
    out.append("        return IDistributor(deploy(distBin(), args));")
    out.append("    }")
    out.append("")

    # --- sizes ---------------------------------------------------------------
    out.append("    function test_sizes() public {")
    out.append(f'        console.log("harness runtime bytes:", uint256({len(harness_rt) // 2}));')
    out.append(f'        console.log("distributor runtime bytes:", uint256({len(dist_rt) // 2}));')
    out.append("    }")
    out.append("")

    # --- deploy gas ------------------------------------------------------------
    out.append("    function test_deploy_gas() public {")
    out.append("        uint256 g = gasleft();")
    out.append("        deploy(harnessBin(), \"\");")
    out.append('        console.log("deploy BenchHarness gas:", g - gasleft());')
    out.append("        g = gasleft();")
    out.append(f"        deployDistributor({tree8['root']});")
    out.append('        console.log("deploy MerkleDistributor gas:", g - gasleft());')
    out.append("    }")
    out.append("")

    # --- single verify ---------------------------------------------------------
    for n in (2, 4, 8, 16):
        s = singles[n]
        out.append(f"    function test_verifySingle_n{n}() public {{")
        out.append(sol_u256_array("proof", s["proof"]))
        out.append(f"        uint256 root_ = {s['root']};")
        out.append(f"        uint256 leaf = {s['leaf']};")
        out.append("        harness.verifySingle(proof, root_, leaf); // warm-up")
        out.append("        uint256 g = gasleft();")
        out.append("        bool ok = harness.verifySingle(proof, root_, leaf);")
        out.append("        uint256 used = g - gasleft();")
        out.append("        assertTrue(ok);")
        out.append(f'        console.log("fe verifySingle n={n} gas:", used);')
        out.append(sol_bytes32_array("oproof", s["proof"]))
        out.append("        oz.verify(oproof, bytes32(root_), bytes32(leaf)); // warm-up")
        out.append("        g = gasleft();")
        out.append("        bool okOz = oz.verify(oproof, bytes32(root_), bytes32(leaf));")
        out.append("        uint256 usedOz = g - gasleft();")
        out.append("        assertTrue(okOz);")
        out.append(f'        console.log("oz verify n={n} gas:", usedOz);')
        out.append("    }")
        out.append("")

    # --- multiproof --------------------------------------------------------------
    for m in multis:
        label = m["label"]
        k = len(m["leaves"])
        out.append(f"    function test_verifyMulti_{label}() public {{")
        out.append(sol_u256_array("proof", m["proof"]))
        out.append(sol_bool_array("flags", m["flags"]))
        out.append(sol_u256_array("leaves", m["leaves"]))
        out.append(f"        uint256 root_ = {m['root']};")
        out.append("        harness.verifyMulti(proof, flags, root_, leaves); // warm-up")
        out.append("        uint256 g = gasleft();")
        out.append("        bool ok = harness.verifyMulti(proof, flags, root_, leaves);")
        out.append("        uint256 used = g - gasleft();")
        out.append("        assertTrue(ok);")
        out.append(f'        console.log("fe verifyMulti {label} gas:", used);')
        out.append(f'        console.log("fe verifyMulti {label} gas per leaf:", used / {k});')
        out.append(sol_bytes32_array("oproof", m["proof"]))
        out.append(sol_bytes32_array("oleaves", m["leaves"]))
        out.append("        oz.multiProofVerify(oproof, flags, bytes32(root_), oleaves); // warm-up")
        out.append("        g = gasleft();")
        out.append("        bool okOz = oz.multiProofVerify(oproof, flags, bytes32(root_), oleaves);")
        out.append("        uint256 usedOz = g - gasleft();")
        out.append("        assertTrue(okOz);")
        out.append(f'        console.log("oz multiProofVerify {label} gas:", usedOz);')
        out.append(f'        console.log("oz multiProofVerify {label} gas per leaf:", usedOz / {k});')
        out.append("    }")
        out.append("")

    # --- fixed-point ---------------------------------------------------------------
    fixed_cases = [
        ("big", "123456789012345678901234567890", "987654321098765432109876543210", "1000000000000000000"),
        ("tie", "1", "1", "2"),
        ("maxima", "0xfffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffe", "0xfffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffe", "0xffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffffff"),
    ]
    for label, a, b, d in fixed_cases:
        out.append(f"    function test_mulDiv_{label}() public {{")
        out.append("        harness.mulDivNearest(" + a + ", " + b + ", " + d + "); // warm-up")
        out.append("        uint256 g = gasleft();")
        out.append("        uint256 r1 = harness.mulDivNearest(" + a + ", " + b + ", " + d + ");")
        out.append("        uint256 u1 = g - gasleft();")
        out.append("        g = gasleft();")
        out.append("        uint256 r2 = harness.mulDivFloor(" + a + ", " + b + ", " + d + ");")
        out.append("        uint256 u2 = g - gasleft();")
        out.append("        assertGe(r1, r2);")
        out.append(f'        console.log("fe mulDivNearest {label} gas:", u1);')
        out.append(f'        console.log("fe mulDivFloor {label} gas:", u2);')
        out.append("    }")
        out.append("")

    out.append("    function test_wadMul() public {")
    out.append("        uint256 a = 1500000000000000000;")
    out.append("        uint256 b = 2500000000000000000;")
    out.append("        harness.wadMulNearest(a, b); // warm-up")
    out.append("        uint256 g = gasleft();")
    out.append("        uint256 r1 = harness.wadMulNearest(a, b);")
    out.append("        uint256 u1 = g - gasleft();")
    out.append("        g = gasleft();")
    out.append("        uint256 r2 = harness.wadMulFloor(a, b);")
    out.append("        uint256 u2 = g - gasleft();")
    out.append("        assertEq(r1, r2);")
    out.append('        console.log("fe wadMulNearest gas:", u1);')
    out.append('        console.log("fe wadMulFloor gas:", u2);')
    out.append("    }")
    out.append("")
    out.append("    function test_powSigned() public {")
    out.append("        harness.powSigned(1050000000000000000, 100); // warm-up")
    out.append("        uint256 g = gasleft();")
    out.append("        harness.powSigned(1050000000000000000, 100);")
    out.append('        console.log("fe powSigned 1.05^100 gas:", g - gasleft());')
    out.append("        g = gasleft();")
    out.append("        harness.powSigned(2000000000000000000, 64);")
    out.append('        console.log("fe powSigned 2^64 gas:", g - gasleft());')
    out.append("        g = gasleft();")
    out.append("        harness.powSigned(2000000000000000000, -10);")
    out.append('        console.log("fe powSigned 2^-10 gas:", g - gasleft());')
    out.append("    }")
    out.append("")
    out.append("    function test_compound() public {")
    out.append("        harness.compound(1000000000000000000000, 50000000000000000, 10); // warm-up")
    out.append("        uint256 g = gasleft();")
    out.append("        harness.compound(1000000000000000000000, 50000000000000000, 10);")
    out.append('        console.log("fe compound 1000 @5% x10 gas:", g - gasleft());')
    out.append("    }")
    out.append("")
    out.append("    function test_leafFromWords() public {")
    out.append(f"        address acct = {sol_address(allocs8[0]['account'])};")
    out.append(f"        harness.leafFromWords(0, acct, {allocs8[0]['amount']}); // warm-up")
    out.append("        uint256 g = gasleft();")
    out.append(f"        uint256 leaf = harness.leafFromWords(0, acct, {allocs8[0]['amount']});")
    out.append(f"        assertEq(leaf, {tree8['leaves'][0]});")
    out.append('        console.log("fe leafFromWords gas:", g - gasleft());')
    out.append("    }")
    out.append("")

    # --- distributor ---------------------------------------------------------------
    # Read-only calls isolate the fixed per-call overhead (dispatcher + ABI
    # decoding) from the compute cost of the verifying/paying calls.
    out.append("    function test_distributor_reads() public {")
    out.append(f"        IDistributor dist = deployDistributor({tree8['root']});")
    out.append("        dist.root(); // warm-up")
    out.append("        uint256 g = gasleft();")
    out.append("        uint256 r = dist.root();")
    out.append(f"        assertEq(r, {tree8['root']});")
    out.append('        console.log("fe distributor root() gas:", g - gasleft());')
    out.append("        g = gasleft();")
    out.append("        bool c = dist.isClaimed(0);")
    out.append("        assertFalse(c);")
    out.append('        console.log("fe distributor isClaimed() gas:", g - gasleft());')
    out.append("        g = gasleft();")
    out.append("        uint256 t = dist.totalClaimed();")
    out.append("        assertEq(t, 0);")
    out.append('        console.log("fe distributor totalClaimed() gas:", g - gasleft());')
    out.append("    }")
    out.append("")

    s8 = singles[8]
    a0 = allocs8[0]
    out.append("    function test_distributor_claim() public {")
    out.append(f"        IDistributor dist = deployDistributor({tree8['root']});")
    out.append("        dist.fund{value: 10 ether}();")
    out.append(sol_u256_array("proof", s8["proof"]))
    out.append(f"        address acct = {sol_address(a0['account'])};")
    out.append("        uint256 g = gasleft();")
    out.append(f"        uint256 payout = dist.claim(proof, 0, acct, {a0['amount']});")
    out.append("        uint256 used = g - gasleft();")
    out.append(f"        assertEq(payout, {a0['amount']});")
    out.append('        console.log("fe distributor claim n=8 gas:", used);')
    out.append("    }")
    out.append("")

    for label, subset in [("k4", "0_1_2_3"), ("k8", "0_1_2_3_4_5_6_7")]:
        v = find_vector(audit, f"mp_8_subset_{subset}")
        idx = [int(x) for x in subset.split("_")]
        k = len(idx)
        out.append(f"    function test_distributor_claimMulti_{label}() public {{")
        out.append(f"        IDistributor dist = deployDistributor({tree8['root']});")
        out.append("        dist.fund{value: 10 ether}();")
        out.append(sol_u256_array("proof", v["proof"]))
        out.append(sol_bool_array("flags", v["flags"]))
        out.append("    uint256[] memory indices = new uint256[](" + str(k) + ");")
        for i, j in enumerate(idx):
            out.append(f"        indices[{i}] = {j};")
        out.append("    address[] memory accounts = new address[](" + str(k) + ");")
        for i, j in enumerate(idx):
            out.append(f"        accounts[{i}] = {sol_address(allocs8[j]['account'])};")
        out.append("    uint256[] memory amounts = new uint256[](" + str(k) + ");")
        for i, j in enumerate(idx):
            out.append(f"        amounts[{i}] = {allocs8[j]['amount']};")
        out.append("        uint256 g = gasleft();")
        out.append("        uint256 total = dist.claimMulti(proof, flags, indices, accounts, amounts);")
        out.append("        uint256 used = g - gasleft();")
        total = sum(allocs8[j]["amount"] for j in idx)
        out.append(f"        assertEq(total, {total});")
        out.append(f'        console.log("fe distributor claimMulti {label} gas:", used);')
        out.append(f'        console.log("fe distributor claimMulti {label} gas per claim:", used / {k});')
        out.append("    }")
        out.append("")

    out.append("}")
    out.append("")

    target = ROOT / "bench" / "test" / "Bench.t.sol"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(out))
    print(f"wrote {target}")


if __name__ == "__main__":
    main()
